#!/usr/bin/python3
"""Desktop-Icons anordnen (läuft bei jeder Anmeldung per Autostart).

GPU-Schnelltest und GPU-Volltest oben links, alle anderen Icons sortiert rechts.

xfdesktop 4.20 speichert Icon-Positionen als Raster pro Monitor in
~/.config/xfce4/desktop/icons.screen0.yaml und übernimmt sie nur für genau diesen
Monitor. Auf jedem neuen Test-PC legt xfdesktop die Icons deshalb erst selbst ab
(Gravity "oben rechts", gesetzt in xfce4-desktop.xml). Dieses Skript liest daraus die
Rastergröße, setzt die gewünschten Positionen und startet xfdesktop neu.
"""
import os
import subprocess
import time

import yaml

HOME = os.path.expanduser("~")
DESK = os.path.join(HOME, "Desktop")
YAML = os.path.join(HOME, ".config/xfce4/desktop/icons.screen0.yaml")
HEADER = "#\n# DO NOT EDIT THIS FILE WHILE XFDESKTOP IS RUNNING\n#\n"

LEFT = [f"{DESK}/1-gpu-schnelltest.desktop", f"{DESK}/2-gpu-volltest.desktop"]
RIGHT = [f"{DESK}/{n}" for n in (
    "3-reports.desktop", "4-nvtop.desktop", "5-readme.desktop", "6-terminal.desktop",
    "7-chromium.desktop", "8-claude.desktop", "9-opencode.desktop")] + [HOME, "/", "trash:///"]


def trust_launchers():
    """xfdesktop führt Starter erst aus, wenn ihre Prüfsumme als vertrauenswürdig markiert ist."""
    for name in sorted(os.listdir(DESK)):
        if name.endswith(".desktop"):
            path = os.path.join(DESK, name)
            out = subprocess.run(["sha256sum", path], capture_output=True, text=True).stdout
            subprocess.run(["gio", "set", "-t", "string", path, "metadata::xfce-exe-checksum",
                            out.split()[0]], check=False)


def is_arranged(cfg):
    icons = cfg.get("icons") or {}
    return all(icons.get(p) == {"row": i, "col": 0} for i, p in enumerate(LEFT))


def arrange(cfg):
    icons = cfg.get("icons") or {}
    placed = {k: v for k, v in icons.items() if k not in LEFT and isinstance(v, dict)}
    if not placed:
        return False
    # rechteste Spalte und deren Höhe = Rasterbreite/-höhe, soweit xfdesktop sie belegt hat
    right_col = max(v["col"] for v in placed.values())
    rows = max(v["row"] for v in placed.values() if v["col"] == right_col) + 1
    if right_col < 1:
        return False
    order = [p for p in RIGHT if p in icons] + sorted(p for p in placed if p not in RIGHT)
    new = {p: {"row": i, "col": 0} for i, p in enumerate(LEFT)}
    for i, p in enumerate(order):
        new[p] = {"row": i % rows, "col": right_col - i // rows}
    cfg["icons"] = new
    return True


def main():
    trust_launchers()
    for _ in range(3):
        # xfdesktop legt die Positionen für einen neuen Monitor kurz nach dem Start ab
        for _ in range(20):
            if os.path.exists(YAML):
                break
            time.sleep(1)
        time.sleep(3)
        try:
            with open(YAML, encoding="utf-8") as f:
                data = yaml.safe_load(f) or {}
        except OSError:
            return
        configs = data.get("configs") or []
        if configs and all(is_arranged(c) for c in configs):
            return
        subprocess.run(["xfdesktop", "--quit"], check=False)
        time.sleep(2)
        with open(YAML, encoding="utf-8") as f:   # neu lesen: xfdesktop speichert beim Beenden
            data = yaml.safe_load(f) or {}
        configs = data.get("configs") or []
        if any([arrange(c) for c in configs]):
            with open(YAML, "w", encoding="utf-8") as f:
                f.write(HEADER)
                yaml.safe_dump(data, f, sort_keys=False, allow_unicode=True)
        subprocess.Popen(["xfdesktop"], start_new_session=True,
                         stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
        time.sleep(5)


if __name__ == "__main__":
    main()
